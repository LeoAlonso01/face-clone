  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='users' AND column_name='id' AND data_type='integer') THEN
    RAISE EXCEPTION 'users.id debe ser integer; revisar antes de migrar';
  END IF;
END $$;
CREATE TABLE IF NOT EXISTS anexo_catalogo (
  clave varchar(30) PRIMARY KEY,
  categoria_id varchar(30) NOT NULL,
  categoria varchar(200) NOT NULL,
  descripcion varchar(500) NOT NULL,
  activo boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS usuario_anexo_config (
  user_id integer PRIMARY KEY REFERENCES users(id),
  revision integer NOT NULL CONSTRAINT ck_anexo_config_revision CHECK (revision > 0),
  confirmado_por integer NOT NULL REFERENCES users(id),
  confirmado_en timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS usuario_anexo_permiso (
  user_id integer NOT NULL REFERENCES usuario_anexo_config(user_id),
  clave varchar(30) NOT NULL REFERENCES anexo_catalogo(clave),
  PRIMARY KEY (user_id, clave)
);
CREATE TABLE IF NOT EXISTS usuario_anexo_historial (
  id serial PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id),
  revision integer NOT NULL,
  actor_id integer NOT NULL REFERENCES users(id),
  fecha timestamptz NOT NULL,
  anteriores json NOT NULL,
  nuevas json NOT NULL,
  motivo varchar(500) NOT NULL,
  CONSTRAINT uq_anexo_historial_revision UNIQUE (user_id, revision)
);
